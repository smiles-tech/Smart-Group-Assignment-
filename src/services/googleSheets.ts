import { CourseSession, GoogleDriveSheet, Student } from '../types';

export function extractSpreadsheetId(input: string): string {
  const trimmed = input.trim();
  // Match https://docs.google.com/spreadsheets/d/{id}/...
  const match = trimmed.match(/\/spreadsheets\/d\/([a-zA-Z0-9-_]+)/);
  if (match && match[1]) {
    return match[1];
  }
  return trimmed;
}

export async function listRecentSpreadsheets(accessToken: string): Promise<GoogleDriveSheet[]> {
  try {
    const query = encodeURIComponent("mimeType='application/vnd.google-apps.spreadsheet' and trashed=false");
    const fields = encodeURIComponent('files(id,name,webViewLink,modifiedTime)');
    const res = await fetch(
      `https://www.googleapis.com/drive/v3/files?q=${query}&fields=${fields}&orderBy=modifiedTime%20desc&pageSize=15`,
      {
        headers: {
          Authorization: `Bearer ${accessToken}`,
        },
      }
    );

    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      console.warn('Could not list drive files:', err);
      return [];
    }

    const data = await res.json();
    return (data.files || []).map((f: any) => ({
      id: f.id,
      name: f.name,
      webViewLink: f.webViewLink || `https://docs.google.com/spreadsheets/d/${f.id}/edit`,
      modifiedTime: f.modifiedTime,
    }));
  } catch (error) {
    console.error('Error fetching drive spreadsheets:', error);
    return [];
  }
}

export async function createCourseSpreadsheet(
  accessToken: string,
  courseCode: string,
  courseTitle: string,
  membersLimit: number
): Promise<{ id: string; url: string; title: string }> {
  const title = `${courseCode} - Group Assignments (${courseTitle})`;

  const payload = {
    properties: {
      title,
    },
    sheets: [
      {
        properties: {
          title: 'Group Assignments',
          gridProperties: {
            frozenRowCount: 2,
          },
        },
      },
    ],
  };

  const res = await fetch('https://sheets.googleapis.com/v4/spreadsheets', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(payload),
  });

  if (!res.ok) {
    const errorData = await res.json().catch(() => ({}));
    throw new Error(errorData.error?.message || `Failed to create spreadsheet (HTTP ${res.status})`);
  }

  const sheetData = await res.json();
  const spreadsheetId = sheetData.spreadsheetId;
  const url = sheetData.spreadsheetUrl || `https://docs.google.com/spreadsheets/d/${spreadsheetId}/edit`;

  // Apply initial header styling & summary row
  try {
    await initializeSpreadsheetStructure(accessToken, spreadsheetId, courseCode, courseTitle, membersLimit);
  } catch (e) {
    console.warn('Could not format newly created sheet styling, data writing will still proceed:', e);
  }

  return {
    id: spreadsheetId,
    url,
    title,
  };
}

async function initializeSpreadsheetStructure(
  accessToken: string,
  spreadsheetId: string,
  courseCode: string,
  courseTitle: string,
  membersLimit: number
) {
  const values = [
    // Row 1: Course Info Banner
    [
      `Course: ${courseCode} - ${courseTitle}`,
      '',
      `Group Limit: ${membersLimit} students/group`,
      '',
      `Generated by QR Group Assign & Sheets Sync`,
      '',
      `Last Updated: ${new Date().toLocaleString()}`,
    ],
    // Row 2: Standard Columns Header
    [
      'Group',
      'Role',
      'Student ID',
      'Full Name',
      'Phone Number',
      'Assigned Time',
      'Notes',
    ],
  ];

  await fetch(
    `https://sheets.googleapis.com/v4/spreadsheets/${spreadsheetId}/values/'Group Assignments'!A1:G2?valueInputOption=USER_ENTERED`,
    {
      method: 'PUT',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        range: "'Group Assignments'!A1:G2",
        majorDimension: 'ROWS',
        values,
      }),
    }
  );
}

export async function syncGroupsToSpreadsheet(
  accessToken: string,
  spreadsheetId: string,
  session: CourseSession,
  students: Student[]
): Promise<{ success: boolean; rowsUpdated: number }> {
  // Sort students by groupNumber asc, then isLeader desc (leader first in group), then joinedAt asc
  const sortedStudents = [...students].sort((a, b) => {
    if (a.groupNumber !== b.groupNumber) {
      return a.groupNumber - b.groupNumber;
    }
    if (a.isLeader && !b.isLeader) return -1;
    if (!a.isLeader && b.isLeader) return 1;
    return new Date(a.joinedAt).getTime() - new Date(b.joinedAt).getTime();
  });

  const headerRows = [
    [
      `Course: ${session.courseCode} - ${session.courseTitle}`,
      '',
      `Max Limit: ${session.membersLimit} per group`,
      `Total Students: ${sortedStudents.length}`,
      `Total Groups: ${sortedStudents.length > 0 ? Math.max(...sortedStudents.map((s) => s.groupNumber)) : 0}`,
      `Tutor: ${session.tutorName}`,
      `Synced: ${new Date().toLocaleString()}`,
    ],
    [
      'Group',
      'Role',
      'Student ID',
      'Full Name',
      'Phone Number',
      'Assigned Time',
      'Status',
    ],
  ];

  const studentRows = sortedStudents.map((s) => [
    `Group ${s.groupNumber}`,
    s.isLeader ? '👑 Group Leader' : 'Member',
    s.studentId,
    s.name,
    s.phone,
    new Date(s.joinedAt).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit', month: 'short', day: 'numeric' }),
    'Assigned',
  ]);

  // Ensure any excess previous rows are cleared
  const totalRowsToWrite = headerRows.length + studentRows.length;
  // Pad with blank rows to clear previous registrations if any were removed
  const maxRows = Math.max(totalRowsToWrite, 50);
  const allValues = [...headerRows, ...studentRows];

  while (allValues.length < maxRows) {
    allValues.push(['', '', '', '', '', '', '']);
  }

  // Check if "Group Assignments" sheet tab exists or write to default sheet
  let targetRange = `'Group Assignments'!A1:G${maxRows}`;

  let updateRes = await fetch(
    `https://sheets.googleapis.com/v4/spreadsheets/${spreadsheetId}/values/${encodeURIComponent(targetRange)}?valueInputOption=USER_ENTERED`,
    {
      method: 'PUT',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        range: targetRange,
        majorDimension: 'ROWS',
        values: allValues,
      }),
    }
  );

  if (!updateRes.ok) {
    // If 'Group Assignments' tab doesn't exist, fallback to first sheet tab range "A1:G..."
    targetRange = `A1:G${maxRows}`;
    updateRes = await fetch(
      `https://sheets.googleapis.com/v4/spreadsheets/${spreadsheetId}/values/${encodeURIComponent(targetRange)}?valueInputOption=USER_ENTERED`,
      {
        method: 'PUT',
        headers: {
          Authorization: `Bearer ${accessToken}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          range: targetRange,
          majorDimension: 'ROWS',
          values: allValues,
        }),
      }
    );
  }

  if (!updateRes.ok) {
    const err = await updateRes.json().catch(() => ({}));
    throw new Error(err.error?.message || `Failed to sync Google Sheet (HTTP ${updateRes.status})`);
  }

  const result = await updateRes.json();
  return {
    success: true,
    rowsUpdated: result.updatedRows || sortedStudents.length,
  };
}

export async function fetchStudentsFromSpreadsheet(
  accessToken: string,
  spreadsheetId: string
): Promise<Student[]> {
  const ranges = ["'Group Assignments'!A3:G100", "A3:G100"];
  let rows: string[][] = [];

  for (const range of ranges) {
    try {
      const res = await fetch(
        `https://sheets.googleapis.com/v4/spreadsheets/${spreadsheetId}/values/${encodeURIComponent(range)}`,
        {
          headers: {
            Authorization: `Bearer ${accessToken}`,
          },
        }
      );
      if (res.ok) {
        const data = await res.json();
        if (data.values && Array.isArray(data.values) && data.values.length > 0) {
          rows = data.values;
          break;
        }
      }
    } catch (e) {
      console.warn(`Could not read range ${range}:`, e);
    }
  }

  const parsedStudents: Student[] = [];

  for (let i = 0; i < rows.length; i++) {
    const row = rows[i];
    if (!row || row.length < 3) continue;

    const groupCol = (row[0] || '').trim();
    const roleCol = (row[1] || '').trim();
    const studentIdCol = (row[2] || '').trim();
    const nameCol = (row[3] || '').trim();
    const phoneCol = (row[4] || '').trim();
    const timeCol = (row[5] || '').trim();

    // Skip empty or invalid rows
    if (!studentIdCol || !nameCol) continue;
    if (studentIdCol === '-' || studentIdCol.toLowerCase().includes('waiting')) continue;

    // Parse group number: e.g. "Group 2" -> 2
    const groupMatch = groupCol.match(/\d+/);
    const groupNumber = groupMatch ? parseInt(groupMatch[0], 10) : 1;
    const isLeader = roleCol.toLowerCase().includes('leader') || roleCol.includes('👑');

    parsedStudents.push({
      id: `sheet_stu_${i}_${Date.now()}`,
      studentId: studentIdCol,
      name: nameCol,
      phone: phoneCol || 'N/A',
      groupNumber,
      isLeader,
      joinedAt: timeCol || new Date().toISOString(),
    });
  }

  return parsedStudents;
}
